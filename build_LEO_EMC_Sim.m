    'Position',[80 70 180 120], ...
    'Maximum','1','SampleTime','cfg.sim.Ts','SamplesPerFrame','cfg.phy.frameBits');

add_block('comm/Error Rate Calculation',[path '/ErrRate'], ...
    'Position',[220 90 360 150]);

add_block('simulink/Sinks/To Workspace',[path '/ToWS'], ...
    'Position',[400 100 480 140], ...
    'VariableName','errRate', 'SaveFormat','Array');

